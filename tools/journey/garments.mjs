        co = cos(a),
        fr = Math.max(0, co),
        back = Math.max(0, -co);
      const x = (0.056 + (0.159 - 0.056) * v) * si,
        z = -0.008 + (0.059 + (0.154 - 0.059) * v) * co + extra * co,
        y = 1.298 - v * (0.067 + 0.094 * fr * fr + 0.045 * back * back) + extra * 0.3;
      return [x + extra * si, y, z];

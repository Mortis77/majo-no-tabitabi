import { TAU, head, chest, torso, arm, leg } from './tailor.mjs';
export function father(g) {
  g.surface(
    'hair',
    17,
    60,
    (u, v) => {
      const a = TAU * u,
        f = Math.max(0, Math.cos(a)),
        t = 0.004 + v * (2.14 - 1.1 * f * f);
      return [
        0.089 * Math.sin(t) * Math.sin(a),
        1.425 + 0.105 * Math.cos(t),
        -0.013 + 0.095 * Math.sin(t) * Math.cos(a),
      ];
    },
    head,
  );
  for (let i = -4; i <= 4; i++) {
    const t = i / 4,
      rad = (v) => Math.max(0.0003, 0.019 * Math.sin(Math.PI * v) ** 0.7);
    g.sweep(
      i % 3 ? 'hair' : 'hairShade',
      [
        [t * 0.029 + 0.019, 1.526, 0.013],
        [t * 0.052 + 0.027, 1.504, 0.043],
        [t * 0.061 + 0.009, 1.471, 0.064],
        [t * 0.067 - 0.005, 1.444 + 0.014 * Math.abs(t), 0.076 - 0.014 * t * t],
      ],
      rad,
      (v) => rad(v) * 0.38,
      [0, 0, 1],
      head,
      16,
      8,
    );
  }
  for (const s of [-1, 1])
    g.sweep(
      'hairShade',
      [
        [s * 0.06, 1.492, 0.023],
        [s * 0.083, 1.465, 0.029],
        [s * 0.088, 1.43, 0.024],
        [s * 0.078, 1.4, 0.026],
      ],
      (t) => 0.01 * (1 - t) + 0.001,
      0.004,
      [s, 0, 0.15],
      head,
    );
  const shirt = [
    [1.303, 0.047, 0.047, -0.01],
    [1.278, 0.087, 0.072, -0.008],
    [1.251, 0.154, 0.08, -0.008],
    [1.197, 0.16, 0.091, -0.001],
    [1.109, 0.141, 0.09, -0.006],
    [1.01, 0.13, 0.085, -0.007],
    [0.927, 0.138, 0.088, -0.006],
  ];
  g.rings('blouse', shirt, { fold: 0.012 });
  for (const s of [-1, 1]) {
    const fixedLeg = (_x, y) => leg(s, y);
    g.surface(
      'blouse',
      7,
      26,
      (u, v) => {
        const a = TAU * u,
          rz = 0.057 + 0.017 * Math.sin(Math.PI * v) - 0.018 * v,
          ry = 0.06 + 0.01 * Math.sin(Math.PI * v) - 0.02 * v;
        return [s * (0.076 + 0.428 * v), 1.225 - 0.008 * v + ry * Math.sin(a), 0.005 + rz * Math.cos(a)];
      },
      arm,
      s < 0,
    );
    g.rings(
      'skirt',
      [
        [0.966, 0.08, 0.095, -0.004],
        [0.875, 0.082, 0.083, -0.005],
        [0.721, 0.073, 0.074, 0.003],
        [0.537, 0.065, 0.063, 0.002],
        [0.372, 0.059, 0.055, -0.015],
        [0.21, 0.052, 0.049, -0.01],
        [0.166, 0.054, 0.048, -0.011],
      ],
      { center: s * 0.064, weight: fixedLeg, fold: 0.035, pleats: 6 },
    );
    g.rings(
      'leather',
      [
        [0.19, 0.048, 0.045, -0.01],
        [0.13, 0.047, 0.048, -0.012],
        [0.084, 0.053, 0.067, 0.005],
        [0.054, 0.055, 0.105, 0.033],
        [0.031, 0.054, 0.105, 0.033],
      ],
      { center: s * 0.054, weight: fixedLeg },
    );
    g.rings(
      'sole',
      [
        [0.044, 0.055, 0.106, 0.033],
        [0.025, 0.054, 0.106, 0.033],
      ],
      { center: s * 0.054, weight: fixedLeg },
    );
  }
  const vest = [
    [1.271, 0.116, 0.077, -0.006, 0.83],
    [1.242, 0.151, 0.086, -0.002, 0.76],
    [1.192, 0.16, 0.097, -0.002, 0.6],
    [1.123, 0.147, 0.104, -0.003, 0.24],
    [1.077, 0.14, 0.099, -0.003, 0.05],
    [0.987, 0.139, 0.097, -0.005, 0.035],
    [0.935, 0.142, 0.099, -0.007, 0.06],
  ];
  g.rings('coat', vest, { fold: 0.008, warp: (a, v) => v * v * 0.017 * (1 - Math.cos(2 * a)) });
  for (const s of [-1, 1])
    g.sweep(
      'collar',
      [
        [s * 0.031, 1.287, 0.032],
        [s * 0.048, 1.261, 0.061],
        [s * 0.046, 1.223, 0.086],
        [s * 0.027, 1.195, 0.099],
      ],
      (t) => 0.011 + 0.009 * Math.sin(Math.PI * t),
      0.003,
      [0, 0, 1],
      torso,
    );
  for (const y of [1.08, 1.037, 0.99, 0.949])
    g.orb('leather', [0.009, y, 0.097], [0.0045, 0.0045, 0.0023], torso);
}

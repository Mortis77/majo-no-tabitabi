import { writeFigureGLB, compareSkeleton } from './writer.mjs';
import { fittingData, REGIONS } from './fitting.mjs';
import { HEAD } from '../assets/akari_head.mjs';

const args = process.argv.slice(2), opt = (f, d) => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : d; };
const want = new Set((opt('--sheets', 'face') || '').split(',').filter(Boolean)), all = want.has('all');
const log = (...a) => console.log(...a), T0 = Date.now();
const NAME = opt('--out', 'akari_base'), DIR = opt('--dir', null) ? path.resolve(ROOT, opt('--dir')) : OUT, REL = path.relative(ROOT, DIR);
if (!/^[\w.-]+$/.test(NAME)) throw new Error('--out takes a file name without folder or extension');
fs.mkdirSync(DIR, { recursive: true });
const fig = await buildFigure({ log, hair: !args.includes('--no-hair'), headCacheDir: DIR === OUT ? null : path.join(DIR, 'cache') });
const { rig, headC } = fig;
const tris = (re) => fig.prims.filter((p) => re.test(p.node)).reduce((s, p) => s + p.idx.length / 3, 0);
log(`figure: ${fig.prims.reduce((s, p) => s + p.idx.length / 3, 0)} tris (face ${tris(/face/)}, body ${tris(/body/)}, hair ${tris(/hair|ribbon/)}, under ${tris(/under/)}); headC ${headC.map((v) => v.toFixed(4))}`);
const save = (name, img) => { R.savePNG(path.join(DIR, name), img); log(`  sheet ${REL}/${name}`); };
const sheet = (name, tiles, cols, title) => save(name, R.sheet(tiles, cols, { title }));
const cam = (c, az, el, d, fov, w, h) => R.orbit(c, az, el, d, fov, w, h);
const shot = (meshes, c, o = {}) => render(meshes, c, { headC, ...o });
const NOHAIR = /Hair|Ribbon/;

// ---------------------------------------------------------------------------------------------------------------- GLB
if (!args.includes('--no-glb')) {
  const byNode = new Map();
  for (const p of fig.prims) { let m = byNode.get(p.node); if (!m) byNode.set(p.node, (m = { node: p.node, prims: [] })); m.prims.push({ material: p.mat, pos: p.pos, nrm: p.nrm, uv: p.uv, idx: p.idx, J: p.J, W: p.W, targets: p.targets }); }
  byNode.get('akari_face').targetNames = SHAPES;
  const file = path.join(ROOT, `assets/models/sculpt/${NAME}.glb`);
  const r = await writeFigureGLB(RIG_SOURCE, file, [...byNode.values()], { meshWorld: rig.meshWorld, extras: { sculpt: `${NAME}: original base figure sculpted for this project (tools/sculpt/figure)` } });
  const same = await compareSkeleton(PRESENT, file);
  log(`wrote assets/models/sculpt/${NAME}.glb: ${(r.bytes / 1024).toFixed(0)} KB, ${r.tris} tris, ${r.verts} verts, materials ${r.materials.join(' ')}; skeleton vs present model: ${JSON.stringify(same)}`);
  fs.writeFileSync(path.join(DIR, 'build.json'), JSON.stringify({ ...r, skeleton: same, perNode: Object.fromEntries([...byNode].map(([k, m]) => [k, m.prims.reduce((s, p) => s + p.idx.length / 3, 0)])), shapes: SHAPES, seconds: (Date.now() - T0) / 1000 }, null, 1));
}


//   -> assets/models/sculpt/akari_base.glb (+ .manifest.json, .regions.json), sheets in .tmp/sculpt/akari_base/
// Pieces are cached (.tmp/sculpt/akari_base/cache): only what changed is contoured again.
//   --out <name>   write assets/models/sculpt/<name>.glb + <name>.regions.json instead (a variant under work beside the shipped file)
//   --dir <path>   working folder for sheets, FITTING.md, build.json and the head's piece cache (default .tmp/sculpt/akari_base)
import fs from 'node:fs';
import path from 'node:path';

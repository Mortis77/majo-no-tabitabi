// node tools/trailer/shots/4-battle/gen-bars33.mjs — writes the bar 33–34 shots: the duel with 鸣 (duel-game, duel-side)
// and 胧牙, the great shade beast of the dusk tree (boss-low, boss-game). Each pair is one performance (same seed and
// inputs) seen by two cameras.
import fs from 'node:fs'; import path from 'node:path'; import url from 'node:url';
const dir = path.dirname(url.fileURLToPath(import.meta.url));
// a low side camera on her and her opponent, smoothed like an operator. o: side offset, back, height, lookH, fov
const sideCam = (o) => `(f, G, R) => {
    const P = G.player, C = G.combat, gy = G.world.heightAt(P.pos.x, P.pos.z);
    let t = (C.duel && C.duel.enemy) || (C.boss && C.boss.enemy) || null;
    if (!t || t.dead) { let best = 1e9; for (const e of C.enemies) if (!e.dead) { const dd = e.pos.distanceTo(P.pos); if (dd < best) { best = dd; t = e; } } }
    let dx = t ? t.pos.x - P.pos.x : Math.sin(P.yaw), dz = t ? t.pos.z - P.pos.z : Math.cos(P.yaw);
    const L = Math.hypot(dx, dz) || 1; dx /= L; dz /= L;
    const S = window.__sc || (window.__sc = { f: -1e9 });
    let px = dz * ${o.sign}, pz = -dx * ${o.sign};
    if (S.sx !== undefined && px * S.sx + pz * S.sz < 0) { px = -px; pz = -pz; }
    S.sx = px; S.sz = pz;
    const span = Math.min(${o.maxSpan}, L);
    const off = ${o.side} + span * ${o.spanK};
    const tp = [P.pos.x - dx * ${o.back} + px * off, gy + ${o.height}, P.pos.z - dz * ${o.back} + pz * off];
    const tl = [P.pos.x + dx * span * ${o.lookK}, gy + ${o.lookH}, P.pos.z + dz * span * ${o.lookK}];
    if (!S.p || !(f >= S.f) || f - S.f > 3) { S.p = tp.slice(); S.l = tl.slice(); }
    const k = Math.min(1, ${o.k} * Math.max(1, f - S.f));
    for (let i = 0; i < 3; i++) { S.p[i] += (tp[i] - S.p[i]) * k; S.l[i] += (tl[i] - S.l[i]) * k * 1.4; }
    S.f = f;
    return { pos: S.p.slice(), look: S.l.slice(), fov: ${o.fov} };
  }`;

const duel = (name, camera) => `// Section 4, bars 33–34: the duel with 胧夜, the rival of the lasting night, on the open evernight flat where the beam
// struggle (b10/b10b) is fought. She locks on, strafes and answers with fire; the rival's spells and hers cross in the
// air. Generated by gen-bars33.mjs.
const CX = 310, CZ = -225, RING = 20; // a wide ring so both cameras stay inside its wall
export default {
  name: '${name}', frames: 240, preroll: 100, seed: 33,
  async setup(G, T, R) {
    R.hud(false); R.wildlife(false); R.life(false); R.weather('clear'); R.freezeFidgets();
    R.spells('all', 2); R.select('fire'); R.fill();
    R.place(CX, CZ + 4, Math.PI);
    await R.settle();
    G.combat.startDuel('oboroyo', { pos: { x: CX, z: CZ }, r: RING }); // cache the rival's model
    await R.step(40); G.combat.clear(); R.clearCombat();
  },
  start(G, T, R) { R.clearCombat(); R.place(CX, CZ + 4, Math.PI); R.fill(); R.keepFull(true); R.select('fire'); R.gameCam({ yaw: 0, pitch: -0.1 });
    G.scene.traverse((o) => { if (o.isMesh && o.geometry && o.geometry.attributes && o.geometry.attributes.corner && o.geometry.attributes.t0) Object.defineProperty(o, 'visible', { get: () => false, set: () => {} }); }); // damage numbers are HUD: keep them out of the picture
  },
  camera: ${camera},
  actions: [
    { f: -90, do: (G) => { G.combat.startDuel('oboroyo', { pos: { x: CX, z: CZ }, r: RING }); } },
    { f: -50, tap: 'KeyT' },
    { f: -20, key: 'KeyA', down: true },
    { f: 8, tap: 'Mouse2' }, { f: 44, tap: 'Mouse2' }, { f: 80, tap: 'Mouse2' },
    { f: 100, key: 'KeyA', down: false }, { f: 104, key: 'KeyD', down: true },
    { f: 116, hold: 'Mouse0', frames: 30 }, { f: 152, tap: 'Mouse2' }, { f: 188, tap: 'Mouse2' },
    { f: 230, key: 'KeyD', down: false },
  ],
  onFrame(f, G, T, R) { if (f % 30 === 0 && f >= 0) { const e = G.combat.duel && G.combat.duel.enemy; R.log('f', f, 'rival', e && e.pos.x.toFixed(1), e && e.pos.z.toFixed(1), 'atk', e && e.atk && e.atk.name); } },
};
`;

const boss = (name, camera) => `// Section 4, bars 33–34: 胧牙, the great shade beast of the dusk tree. It leaps at her, she dashes clear of the
// landing, locks on and throws talismans into it. Generated by gen-bars33.mjs.
const AX = -30, AZ = -170;
export default {
  name: '${name}', frames: 340, preroll: 90, seed: 34,
  async setup(G, T, R) {
    R.hud(false); R.wildlife(false); R.life(false); R.weather('clear'); R.freezeFidgets();
    R.spells('all', 2); R.select('sun'); R.fill();
    R.place(AX, AZ + 12, Math.PI);
    await R.settle();
    G.combat.startBoss('oboroga'); // cache the beast's model
    await R.step(40); G.combat.clear(); R.clearCombat();
  },
  start(G, T, R) { R.clearCombat(); R.place(AX, AZ + 12, Math.PI); R.fill(); R.keepFull(true); R.select('sun'); R.gameCam({ yaw: 0, pitch: -0.05 });
    G.scene.traverse((o) => { if (o.isMesh && o.geometry && o.geometry.attributes && o.geometry.attributes.corner && o.geometry.attributes.t0) Object.defineProperty(o, 'visible', { get: () => false, set: () => {} }); }); // damage numbers are HUD: keep them out of the picture
    window.__bs = { leapF: null, dodged: false, up: null }; },
  camera: ${camera},
  actions: [
    { f: -80, do: (G) => { G.combat.startBoss('oboroga'); } },
    { f: -40, tap: 'KeyT' },
  ],
  onFrame(f, G, T, R) {
    const S = window.__bs; if (!S) return;
    const b = G.combat.boss, e = b && b.enemy;
    if (S.up !== null && f >= S.up) { T.key('KeyA', false); S.up = null; }
    if (e && S.leapF === null && e.atk && e.atk.name === 'leap' && e.atk.fired) { S.leapF = f; R.log('LEAP fired f', f); }
    if (S.leapF !== null && !S.dodged && f >= S.leapF + 30) { S.dodged = true; T.key('KeyA', true); S.up = f + 24; setTimeout(() => { T.key('KeyQ', true); setTimeout(() => T.key('KeyQ', false), 34); }, 17); R.log('DODGE f', f); }
    if (S.dodged && f >= S.leapF + 80 && f < S.leapF + 81) { T.key('Mouse0', true); setTimeout(() => T.key('Mouse0', false), 900); }
    if (S.dodged && f === S.leapF + 150) { T.key('Mouse2', true); setTimeout(() => T.key('Mouse2', false), 34); }
    if (f % 30 === 0 && f >= 0 && e) R.log('f', f, 'beast', e.pos.x.toFixed(1), e.pos.z.toFixed(1), 'atk', e.atk && e.atk.name, 'P', G.player.pos.x.toFixed(1), G.player.pos.z.toFixed(1));
  },
};
`;
// the duel: side-on from inside the ring, both casters in frame, the spells crossing between them
const duelSide = `(f, G, R) => {
    const P = G.player, e = G.combat.duel && G.combat.duel.enemy, gy = G.world.heightAt(310, -225);
    const ex = e ? e.pos.x : 310, ez = e ? e.pos.z : -233;
    let dx = ex - P.pos.x, dz = ez - P.pos.z; const L = Math.hypot(dx, dz) || 1; dx /= L; dz /= L;
    const S = window.__sc || (window.__sc = { f: -1e9 });
    let px = dz, pz = -dx; if (px < 0) { px = -px; pz = -pz; } // always from the open east side (as the struggle)
    const mx = (P.pos.x + ex) / 2, mz = (P.pos.z + ez) / 2, d = 4 + L * 0.55;
    const tp = [mx + px * d - dx * 0.8, gy + 0.85, mz + pz * d - dz * 0.8], tl = [mx - dx * 0.6, gy + 1.25, mz - dz * 0.6];
    if (!S.p || !(f >= S.f) || f - S.f > 3) { S.p = tp.slice(); S.l = tl.slice(); }
    const k = Math.min(1, 0.05 * Math.max(1, f - S.f));
    for (let i = 0; i < 3; i++) { S.p[i] += (tp[i] - S.p[i]) * k; S.l[i] += (tl[i] - S.l[i]) * k; }
    S.f = f;
    return { pos: S.p.slice(), look: S.l.slice(), fov: 44 };
  }`;
const bossLow = sideCam({ sign: 1, side: 1.4, spanK: 0.05, back: 5.0, height: 0.45, lookK: 0.6, lookH: 3.2, maxSpan: 20, k: 0.07, fov: 52 });
fs.writeFileSync(path.join(dir, 'duel-game.js'), duel('duel-game', "'game'"));
fs.writeFileSync(path.join(dir, 'duel-side.js'), duel('duel-side', duelSide));
fs.writeFileSync(path.join(dir, 'boss-low.js'), boss('boss-low', bossLow));
fs.writeFileSync(path.join(dir, 'boss-game.js'), boss('boss-game', "'game'"));
